const stored = typeof window !== "undefined" ? window.localStorage.getItem("gk_lang") : null;

void i18n.use(initReactI18next).init({
  resources: { en: { t: en }, hi: { t: hi } },
  lng: stored ?? "en",
  fallbackLng: "en",
  defaultNS: "t",
  interpolation: { escapeValue: false },
});

export function setLang(lang: "en" | "hi") {
  void i18n.changeLanguage(lang);
  if (typeof window !== "undefined") window.localStorage.setItem("gk_lang", lang);
}

export default i18n;
